export function t(key, vars) {
  let s = (STR[LANG] && STR[LANG][key]) || STR.en[key] || key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
  return s;
}
